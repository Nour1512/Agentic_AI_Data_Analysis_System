import os
import uuid
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from typing import List, Optional

from agents_schema.sql import DataRequest
from agents.sql_agent import sql_agent_app
from dotenv import load_dotenv

load_dotenv()

app = FastAPI(title="SQL Agent API")

# Allow CORS for the frontend
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

class QueryRequest(BaseModel):
    query_intent: str
    tables_required: List[str]

@app.post("/api/query")
async def process_query(req: QueryRequest):
    request_data = DataRequest(
        request_id=str(uuid.uuid4()),
        query_intent=req.query_intent,
        tables_required=req.tables_required,
        expected_format="tabular"
    )
    
    initial_state = {
        "request": request_data
    }
    
    try:
        result_state = sql_agent_app.invoke(initial_state)
        response = result_state.get("response")
        
        if not response:
            raise HTTPException(status_code=500, detail="No response generated by the agent.")
            
        return response
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="0.0.0.0", port=8000)
