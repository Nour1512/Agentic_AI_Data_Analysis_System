"""Report Agent for generating professional analytical reports from validated analysis results."""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from typing import Any, Protocol

from agents_schema.report import ReportRequest, ReportResponse, StructuredReport
from agents_schema.common import ErrorInfo
from prompts.report_prompt import REPORT_SYSTEM_PROMPT


logger = logging.getLogger(__name__)


class LLMClient(Protocol):
    """Minimal interface required from the shared LLM client."""

    def generate(self, system_prompt: str, user_prompt: str) -> str:
        """Generate text from the configured LLM."""


class ReportAgent:
    """Generate a professional analytical report from validated analysis results."""

    def __init__(
        self,
        llm_client: LLMClient,
        output_dir: str = "reports",
    ) -> None:
        self.llm_client = llm_client
        self.output_dir = Path(output_dir)

    def run(self, report_request: ReportRequest) -> ReportResponse:
        """Generate and save a report, returning both .docx path and Markdown content."""

        self._validate_request(report_request)

        logger.info(
            "[REPORT] Report Agent started for request_id=%s",
            report_request.request_id,
        )
        logger.info(
            "[REPORT] Input — title: %s, findings: %d, recommendations: %d, "
            "data_rows: %d, data_columns: %d, charts: %d",
            report_request.title,
            len(report_request.key_findings),
            len(report_request.recommendations),
            len(report_request.data_rows),
            len(report_request.data_columns),
            len(report_request.charts),
        )

        try:
            user_prompt = self._build_user_prompt(report_request)

            logger.info("[REPORT] Sending prompt to LLM (%d chars)", len(user_prompt))

            report_content = self.llm_client.generate(
                system_prompt=REPORT_SYSTEM_PROMPT,
                user_prompt=user_prompt,
            )

            # Strip markdown fences if LLM wrapped the JSON
            if report_content.startswith("```"):
                report_content = re.sub(r"^```(?:json)?\s*\n|\n```$", "", report_content, flags=re.MULTILINE).strip()
            
            logger.info("[REPORT] LLM returned report JSON (%d chars)", len(report_content))

            # Parse JSON
            try:
                report_data = json.loads(report_content)
                structured_report = StructuredReport(**report_data)
            except json.JSONDecodeError as e:
                logger.error("[REPORT] LLM output was not valid JSON: %s\n%s", e, report_content)
                raise ValueError(f"LLM failed to output valid JSON: {e}")
            except Exception as e:
                logger.error("[REPORT] Failed to validate StructuredReport: %s\n%s", e, report_content)
                raise ValueError(f"LLM JSON did not match StructuredReport schema: {e}")

            # Inject the strictly validated charts and canonical metrics
            # The LLM shouldn't modify these, so we append them directly from the request.
            structured_report.visualizations = report_request.charts

            return ReportResponse(
                request_id=report_request.request_id,
                success=True,
                structured_report=structured_report,
                report_html=None,  # Will be generated by the Renderer
                report_path=None   # Will be generated by the Renderer
            )

        except Exception as exc:
            logger.exception(
                "[REPORT] Report Agent FAILED for request_id=%s: %s",
                report_request.request_id, exc,
            )

            return ReportResponse(
                request_id=report_request.request_id,
                success=False,
                error=ErrorInfo(
                    code="REPORT_ERROR",
                    message="Failed to generate the report.",
                    details=str(exc),
                ),
            )

    @staticmethod
    def _validate_request(report_request: ReportRequest) -> None:
        """Validate required report information."""

        if not report_request.request_id.strip():
            raise ValueError(
                "ReportRequest.request_id cannot be empty."
            )

        if not report_request.title.strip():
            raise ValueError(
                "ReportRequest.title cannot be empty."
            )

        if not report_request.original_question.strip():
            raise ValueError(
                "ReportRequest.original_question cannot be empty."
            )

    @staticmethod
    def _build_user_prompt(report_request: ReportRequest) -> str:
        """Build a well-formatted prompt with properly structured data."""

        # Format key findings as readable bullet points
        findings_text = "\n".join(
            f"  - {f}" for f in report_request.key_findings
        ) if report_request.key_findings else "  (No key findings provided)"

        # Format business context
        context_text = "\n".join(
            f"  - {c}" for c in report_request.business_context
        ) if report_request.business_context else "  (No business context provided)"

        # Format recommendations
        recommendations_text = "\n".join(
            f"  - {r}" for r in report_request.recommendations
        ) if report_request.recommendations else "  (No recommendations provided)"

        # Format chart info
        # We no longer instruct the LLM to output markdown images.
        # Charts will be injected natively by the rendering engine.
        if report_request.charts:
            charts_text = "The following charts have been generated and will be automatically inserted into the Visual Analysis section. You may reference them in your detailed analysis:\n\n"
            for i, c in enumerate(report_request.charts):
                charts_text += f"Chart {i+1}: {c.title} ({c.chart_type})\n"
                if c.insight:
                    charts_text += f"Insight: {c.insight}\n"
                charts_text += "\n"
        else:
            charts_text = "  (No visualizations were generated)"

        # Format canonical metrics — AUTHORITATIVE numbers
        canonical_metrics_text = ""
        if report_request.canonical_metrics:
            cm = report_request.canonical_metrics
            lines = []
            lines.append(f"  Record Count: {cm.get('record_count', 'N/A')}")
            lines.append(f"  Columns: {', '.join(cm.get('column_names', []))}")

            for col, summary in cm.get("numeric_summaries", {}).items():
                col_label = col.replace("_", " ").title()
                lines.append(f"  {col_label}:")
                lines.append(f"    Total: {summary.get('total', 'N/A')}")
                lines.append(f"    Average: {summary.get('average', 'N/A')}")
                lines.append(f"    Min: {summary.get('min', 'N/A')}")
                lines.append(f"    Max: {summary.get('max', 'N/A')}")
                lines.append(f"    Median: {summary.get('median', 'N/A')}")

            for col, cat_info in cm.get("top_categories", {}).items():
                col_label = col.replace("_", " ").title()
                lines.append(f"  Top {cat_info.get('category_field', col).replace('_', ' ').title()}: {cat_info.get('top', 'N/A')} ({cat_info.get('top_value', 'N/A')})")
                lines.append(f"  Bottom {cat_info.get('category_field', col).replace('_', ' ').title()}: {cat_info.get('bottom', 'N/A')} ({cat_info.get('bottom_value', 'N/A')})")

            canonical_metrics_text = "\n".join(lines)

        # Format data sample as a readable table
        data_sample_text = ""
        if report_request.data_rows:
            sample = report_request.data_rows[:15]  # Show first 15 rows

            if report_request.data_columns:
                cols = report_request.data_columns
            elif sample:
                cols = list(sample[0].keys())
            else:
                cols = []

            if cols:
                # Build markdown table
                header = "| " + " | ".join(str(c) for c in cols) + " |"
                separator = "| " + " | ".join("---" for _ in cols) + " |"
                rows = []
                for row in sample:
                    values = [str(row.get(c, "")) for c in cols]
                    rows.append("| " + " | ".join(values) + " |")

                data_sample_text = f"""
Data Sample ({len(report_request.data_rows)} total records, showing first {len(sample)}):

{header}
{separator}
""" + "\n".join(rows)
        else:
            data_sample_text = "  (No data rows available)"

        # Format additional context
        additional_text = "\n".join(
            f"  - {a}" for a in report_request.additional_context
        ) if report_request.additional_context else ""

        prompt = f"""Create a professional analytical report using ONLY the validated
information provided below. Do not invent numbers, findings, conclusions,
or recommendations.

REPORT TITLE:
  {report_request.title}

ORIGINAL USER QUESTION:
  {report_request.original_question}

ANALYSIS SUMMARY:
  {report_request.summary}

==================================================
CANONICAL METRICS (AUTHORITATIVE — USE EXACTLY THESE NUMBERS)
==================================================

The following metrics were computed directly from the actual SQL query results.
You MUST use EXACTLY these numbers in your report. Do NOT recalculate, round
differently, or invent alternative totals. Every number in your report must
match these canonical values.

{canonical_metrics_text if canonical_metrics_text else "  (No canonical metrics available)"}

==================================================

KEY FINDINGS:
{findings_text}

BUSINESS CONTEXT:
{context_text}

RECOMMENDATIONS:
{recommendations_text}

VISUALIZATIONS GENERATED:
{charts_text}

{data_sample_text}

TOTAL RECORDS: {report_request.row_count}
COLUMNS: {', '.join(report_request.data_columns) if report_request.data_columns else '(Not available)'}

{f'ADDITIONAL CONTEXT:{chr(10)}{additional_text}' if additional_text else ''}

Generate the report now. Start directly with "## 1. Executive Summary".
"""
        return prompt

    @staticmethod
    def _clean_markdown(text: str) -> str:
        """Strip markdown fences if they exist (kept for compatibility if needed)."""
        if text.startswith("```"):
            return re.sub(r"^```[a-zA-Z]*\n|\n```$", "", text, flags=re.MULTILINE).strip()
        return text